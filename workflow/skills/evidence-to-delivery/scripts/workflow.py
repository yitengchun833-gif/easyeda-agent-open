MARKER = "<!-- generated by evidence-workflow; edit through workflow.py -->"
IDENT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,99}$")
DOMAINS = ("analysis", "schematic", "pcb", "other")


def now():
    return datetime.now(timezone.utc).isoformat()


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":")).encode()).hexdigest()


def file_hash(path, hashes=None):
    path = Path(path).resolve()
    if hashes is not None and path in hashes:
        return hashes[path]
    with path.open("rb") as f:
        value = hashlib.file_digest(f, "sha256").hexdigest()
    if hashes is not None:
        hashes[path] = value
    return value


def write(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent,
                                     delete=False, suffix=".tmp") as f:
        f.write(data if isinstance(data, str) else json.dumps(data, ensure_ascii=False, indent=2))
        tmp = f.name
    try:
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def identity(value):
    require(isinstance(value, str) and IDENT.fullmatch(value), "invalid stable ID")
    return value


def resolve(root, value):
    p = Path(value)
    return (root / p).resolve() if not p.is_absolute() else p.resolve()


def source_value(root, spec, hashes=None):
    """A reference is pinned to selected anchors, not an entire parsed JSON hash."""
    identity(spec["id"])
    require(spec.get("kind") in ("document", "decision", "observation"), "source kind required")
    if spec["kind"] == "document":
        manifest_path = resolve(root, spec["manifest"])
        m = read(manifest_path)
        require(m["parse_status"] in ("success", "partial"), "source parsing failed")
        require(nonempty(m.get("index_path")), "source has no structured index")
        original = resolve(manifest_path.parent, m["source_path"])
        require(original.is_file() and file_hash(original, hashes) == m["source_hash"],
                "source changed or missing: reparse before registration")
        index = read(resolve(manifest_path.parent, m["index_path"]))
        anchors = spec["anchors"]
        require(isinstance(anchors, list) and anchors, "select evidence anchors")
        selected = [index["items"][a] for a in anchors]
        for entry in selected:
            if entry.get("asset"):
                asset = resolve(manifest_path.parent, entry["asset"])
                require(asset.is_file() and file_hash(asset, hashes) == entry["asset_hash"],
                        "extracted visual asset changed or missing")
        content = [{"text": x["text"], "label": x["label"], "asset_hash": x.get("asset_hash")}
                   for x in selected]
        spec = dict(spec, manifest=str(manifest_path), source_version=m["document_version"],
                    source_hash=m["source_hash"], locations=[x["locations"] for x in selected])
    else:
        require(nonempty(spec.get("text")) and nonempty(spec.get("locator")),
                "decision/observation requires text and original locator")
        content = {"text": spec["text"], "locator": spec["locator"]}
    return dict(spec, fingerprint=digest(content))


def source_issue(root, source, hashes=None):
    if source["kind"] != "document":
        return None
    try:
        fresh = source_value(root, source, hashes)
        if fresh["source_hash"] != source["source_hash"]:
            return "document version changed; refresh source and review"
        if fresh["fingerprint"] != source["fingerprint"]:
            return "selected evidence changed"
    except (ValueError, OSError, KeyError, TypeError) as e:
        return str(e)
    return None


def validate_jev(policy):
    require(isinstance(policy, dict), "jev policy required: requests or skip_reason")
    if set(policy) == {"skip_reason"}:
        require(nonempty(policy["skip_reason"]), "Jev skip requires a concrete deterministic reason")
        return
    require(set(policy) == {"requests"} and isinstance(policy["requests"], dict)
            and 1 <= len(policy["requests"]) <= 10, "jev requests must contain 1-10 named decisions")
    for key, request in policy["requests"].items():
        identity(key)
        require(isinstance(request, dict) and {"goal", "stage", "candidates"} <= set(request)
                <= {"goal", "stage", "candidates", "threshold"}, "invalid Jev request")
        require(nonempty(request["goal"]) and nonempty(request["stage"]), "decision goal/stage required")
        candidates = request["candidates"]
        require(isinstance(candidates, list) and 2 <= len(candidates) <= 6, "decision needs 2-6 filtered candidates")
        require(all(isinstance(c, dict) and set(c) == {"id", "label", "evidence"}
                    and all(nonempty(v) for v in c.values()) for c in candidates), "candidate evidence required")
        require(len({c["id"] for c in candidates}) == len(candidates), "duplicate candidate IDs")


def call_jev(request):
    # Fixed local entry; candidate text is data, never command text. No EDA process is called.
    entry = Path(__file__).resolve().parents[3] / "components/easyeda-mcp/src/jev.mjs"
    try:
        cp = subprocess.run(["node", str(entry), "-"], input=json.dumps(request),
                            text=True, encoding="utf-8", capture_output=True, timeout=15)
        if cp.returncode != 0:
            return {"status": "needs_input", "attempted": False, "fallback": "jev_process_error"}
        report = json.loads(cp.stdout)
        require(isinstance(report, dict), "invalid Jev report")
        return report
    except (OSError, subprocess.TimeoutExpired, ValueError):
        return {"status": "needs_input", "attempted": False, "fallback": "jev_unavailable"}


def decisions_for(state, key, retry=False):
    policy = state["plan"][key].get("jev")
    if policy is None:
        return {}  # No semantic decision: no call or repeated skip receipt.
    validate_jev(policy)
    if "skip_reason" in policy:
        return {"skip_reason": policy["skip_reason"]}
    previous = next((r.get("jev", {}) for r in reversed(state["results"])
                     if r["item"] == key and r["basis"] == basis(state, key) and "jev" in r), {})
    reports = {}
    for name, request in policy["requests"].items():
        old = previous.get("decisions", {}).get(name)
        # Reuse the exact current-basis decision; retry failures only on explicit retry.
        if old and old.get("request_hash") == digest(request) and not (
                retry and old.get("report", {}).get("status") != "recommended"):
            reports[name] = dict(old, reused=True)
        else:
            reports[name] = {"request_hash": digest(request), "report": call_jev(request), "reused": False}
    return {"decisions": reports, "calls_this_run": sum(1 for item in reports.values()
            if not item["reused"] and item["report"].get("attempted") is True)}


def validate_plan(plan, sources, root=None):
    require(isinstance(plan, dict), "plan must be an object")
    for key, item in plan.items():
        identity(key)
        require(key not in sources, "plan/source IDs must be distinct")
        require(nonempty(item.get("description")) and nonempty(item.get("acceptance")),
                key + ": description and acceptance required")
        require("domain" not in item or item["domain"] in DOMAINS, key + ": invalid execution domain")
        for field in ("sources", "depends_on", "objects"):
            require(isinstance(item.get(field), list) and
                    all(nonempty(x) for x in item[field]), key + ": invalid " + field)
        require(item["sources"], key + ": evidence required")
        require(set(item["sources"]) <= sources.keys(), key + ": unknown evidence")
        require(set(item["depends_on"]) <= plan.keys(), key + ": missing dependency")
        require(key not in item["depends_on"], key + ": self dependency")
        if "jev" in item:
            validate_jev(item["jev"])
        checks = item.get("required_checks", [])
        require(isinstance(checks, list) and all(nonempty(c) for c in checks) and
                len(checks) == len(set(checks)), key + ": invalid required_checks")
        require("execution_rules" not in checks or "rule_application" in checks,
                key + ": rule preflight requires final rule_application coverage")
        open_path = item.get("domain") == "schematic" and "open_plan" in item
        open_required = {"open_stage_receipt", "open_requirements", "open_target_check", "visual_review", "persistence"}
        local_required = {"open_stage_receipt", "open_local_rules", "open_requirements", "visual_review", "persistence"}
        if open_path and root is not None:
            _, drawing, _ = open_receipts.plan_inputs(sys.modules[__name__], root, item["open_plan"])
            if drawing.get("acceptanceScope", "page") == "local_display":
                open_required = local_required
            require({"execution_rules", "rule_application"} <= set(checks) or open_required <= set(checks),
                    key + ": Open checks do not match the approved acceptance scope")
        require(item.get("domain") not in ("schematic", "pcb") or
                {"execution_rules", "rule_application"} <= set(checks) or
                (open_path and (open_required <= set(checks) or local_required <= set(checks))),
                key + ": hardware execution requires legacy gates or bound Open checks plus visual and persistence evidence")
        if "pcb_constraint_ir" in item:
            require(item.get("domain") == "pcb", key + ": PCB IR belongs to a PCB module")
            pcb_constraints.validate(sys.modules[__name__], item["pcb_constraint_ir"])
        if "pcb_checks" in item:
            require(item.get("domain") == "pcb", key + ": PCB checks belong to a PCB module")
            pcb_constraints.validate_checks(sys.modules[__name__], item["pcb_checks"],
                                            item["pcb_constraint_ir"]["target"], item["sources"])
            require("pcb_professional_checks" in checks, key + ": professional checks must be required")
        if "open_plan" in item:
            open_receipts.validate(require, item["open_plan"], item.get("domain"))
    visiting, done = set(), set()

    def visit(key):
        require(key not in visiting, "dependency cycle: " + key)
        if key in done:
            return
        visiting.add(key)
        for dep in plan[key]["depends_on"]:
            visit(dep)
        visiting.remove(key)
        done.add(key)
    for key in plan:
        visit(key)


def impact(state, changed):
    """Conservative closure of registered references and shared objects only."""
    plans, sources = state["plan"], state["sources"]
    require(changed in plans or changed in sources, "unknown changed ID")
    reasons = {changed: "changed plan"} if changed in plans else {}
    if changed in sources:
        reasons.update({k: "uses " + changed for k, p in plans.items() if changed in p["sources"]})
    while True:
        before = len(reasons)
        objects = {o for k in reasons for o in plans[k]["objects"]}
        for key, p in plans.items():
            deps = set(p["depends_on"]) & reasons.keys()
            shared = set(p["objects"]) & objects
            if key not in reasons and (deps or shared):
                reasons[key] = "dependency/shared object: " + ", ".join(sorted(deps | shared))
        if len(reasons) == before:
            return reasons


def basis(state, key, trail=None):
    p = state["plan"][key]
    value = {"revision": p["revision"], "review_epoch": p.get("review_epoch", 0),
                   "sources": {s: state["sources"][s]["fingerprint"] for s in p["sources"]},
                   "dependencies": {d: basis(state, d) for d in p["depends_on"]}}
    if "open_plan" in p:
        value["open_plan"] = p["open_plan"]
    return digest(value)


def status(root, state):
    require(all(isinstance(r, dict) and all(k in r for k in
                ("item", "basis", "revision", "status", "note", "evidence"))
                for r in state["results"]),
            "execution records missing required fields; inspect and migrate legacy/direct edits before recovery")
    # One read-only query snapshot; never reuse hashes across calls or mutations.
    hashes = {}
    issues = {s: issue for s, value in state["sources"].items()
              if (issue := source_issue(root, value, hashes))}
    affected = set(state["reviews"])
    open_issues = {}
    for key, p in state["plan"].items():
        if "open_plan" in p:
            try:
                _, drawing, _ = open_receipts.plan_inputs(sys.modules[__name__], root, p["open_plan"], hashes)
                if "execution_rules" not in p.get("required_checks", []):
                    expected = {"open_stage_receipt", "open_requirements", "visual_review", "persistence"}
                    expected.add("open_local_rules" if drawing.get("acceptanceScope", "page") == "local_display" else "open_target_check")
                    require(expected <= set(p.get("required_checks", [])), "Open acceptance scope/checks mismatch")
            except (ValueError, OSError, KeyError, TypeError) as exc:
                open_issues[key] = str(exc)
                affected.update(impact(state, key))
    for s in issues:
        affected.update(impact(state, s))
    rows, recovery = {}, {}
    for key, p in state["plan"].items():
        current_basis = basis(state, key)
        latest = next((r for r in reversed(state["results"])
                       if r["item"] == key and r["basis"] == current_basis), None)
        state_name = latest["status"] if latest else "pending"
        if latest:
            for evidence in latest["evidence"]:
                path = resolve(root, evidence["path"])
                if not path.is_file() or file_hash(path, hashes) != evidence["hash"]:
                    state_name = "needs_review"
        if key in affected:
            state_name = "needs_review"
        rows[key] = {"revision": p["revision"], "status": state_name}
        unfinished = next((r for r in reversed(state["results"]) if r["item"] == key and not r.get("preparation_only")), None)
        if unfinished and unfinished["status"] in ("in_progress", "partial", "blocked"):
            hardware = p.get("domain") in ("schematic", "pcb")
            recovery[key] = {"revision": p["revision"], "record_revision": unfinished["revision"],
                "readback_required": hardware, "last_note": unfinished["note"],
                "next": "Read back the target and completed actions; resume only remaining actions."
                        if hardware else "Inspect the recorded blocker and current evidence before resuming."}
    # Failed or unavailable upstream evidence blocks downstream readiness.
    while True:
        updated = False
        for key, p in state["plan"].items():
            if rows[key]["status"] == "verified" and any(
                    rows[d]["status"] != "verified" for d in p["depends_on"]):
                rows[key]["status"] = "needs_review"
                updated = True
        if not updated:
            break
    ready = [k for k, p in state["plan"].items()
             if rows[k]["status"] == "pending" and
             not recovery.get(k, {}).get("readback_required") and
             all(rows[d]["status"] == "verified" for d in p["depends_on"])]
    return {"generation": state["generation"], "items": rows, "ready": ready,
            "source_issues": issues, "open_plan_issues": open_issues, "reviews": state["reviews"],
            "pending_changes": list(state["pending"]), "context": state["context"], "recovery": recovery}


def check_evidence(root, plan, op, hashes=None, application_phase="after_reopen"):
    """Named check coverage augments the existing result; it is not a second state."""
    required = [k for k in plan.get("required_checks", []) if k != "pcb_professional_checks" or plan.get("domain") != "pcb"]
    checks = op.get("checks", [])
    require(isinstance(checks, list), "checks must be an array")
    rows, paths, reports = {}, [], {}
    open_path = plan.get("domain") == "schematic" and "open_plan" in plan and "execution_rules" not in required
    require(op.get("status") != "verified" or "open_persistence" not in op or open_path,
            "Native Open persistence cannot be mixed with legacy acceptance")
    if open_path and op["status"] in ("in_progress", "verified"):
        _, drawing, dependencies = open_receipts.plan_inputs(sys.modules[__name__], root, plan["open_plan"], hashes)
        require(drawing.get("confirmation", {}).get("status") == "confirmed" and drawing.get("requirements"),
                "Open execution needs a confirmed plan with explicit requirements")
        before = [r for r in drawing["requirements"] if r["when"] == "before_write" and r["severity"] == "error"]
        require(before and all(r["method"] == "checker" and r["check"] == "source_binding" for r in before),
                "Open preconditions need supported source-bound evidence")
        paths.extend(dependencies)
        expected = {"open_stage_receipt", "open_requirements", "visual_review", "persistence"}
        expected.add("open_local_rules" if drawing.get("acceptanceScope", "page") == "local_display" else "open_target_check")
        require(expected <= set(required), "Open required_checks do not cover the declared acceptance scope")
    for check in checks:
        require(isinstance(check, dict), "check must be an object")
        key = check.get("id")
        require(plan.get("domain") != "pcb" or key != "pcb_professional_checks",
                "PCB professional results are generated by current read-only review; cannot be self-declared")
        require(nonempty(key) and key not in rows, "missing or duplicate check id")
        require(check.get("status") in ("pass", "fail", "unknown"), "invalid check status")
        require(nonempty(check.get("note")), "check requires an actual observation note")
        evidence = check.get("evidence", [])
        require(isinstance(evidence, list) and evidence and all(nonempty(x) for x in evidence),
                "check requires file evidence")
        paths.extend(evidence)
        if check.get("report"):
            path = resolve(root, check["report"])
            report = read(path)
            require(isinstance(report, dict), "check report must be an object")
            require(isinstance(report.get("passed"), bool), "check report needs boolean passed")
            require(check["status"] != "pass" or report["passed"] is True,
                    "failed report cannot be labelled pass")
            reports[key] = (path, report)
            paths.append(str(path))
            for field in ("inputs", "evidence_files"):
                declared_hashes = report.get(field, {})
                require(isinstance(declared_hashes, dict), "report hashes must be an object")
                for filename, digest_value in declared_hashes.items():
                    dependency = resolve(path.parent, filename)
                    require(dependency.is_file() and file_hash(dependency, hashes) == digest_value,
                            "report input changed: " + filename)
                    paths.append(str(dependency))
        rows[key] = check
    if "execution_rules" in required and op["status"] in ("in_progress", "verified"):
        require("execution_rules" in reports and rows["execution_rules"]["status"] == "pass",
                "confirmed execution_rules report required before starting")
        gate = reports["execution_rules"][1]
        rules = gate.get("execution_rules", {})
        require(isinstance(rules, dict), "execution_rules report must be an object")
        effective = rules.get("effective_ids")
        require(gate.get("passed") is True and gate.get("inputs") and
                rules.get("confirmed") is True and nonempty(rules.get("version")) and
                nonempty(rules.get("sha256")) and isinstance(effective, list) and effective and
                all(nonempty(key) for key in effective) and len(effective) == len(set(effective)),
                "execution_rules must be confirmed, current and nonempty")
        if op["status"] == "verified":
            require("rule_application" in reports, "rule_application report required")
            path, final = reports["rule_application"]
            require(final.get("phase", "after_reopen") == application_phase,
                    "rule_application phase does not satisfy this operation")
            require(final.get("rule_binding") == {k: rules[k] for k in ("version", "sha256")},
                    "rule_application targets a different rule revision")
            observations = final.get("checks", [])
            require(isinstance(observations, list) and all(isinstance(c, dict) for c in observations),
                    "rule_application checks must be objects")
            actual = {}
            for check in observations:
                covered = check.get("rule_ids", [check.get("id")])
                require(isinstance(covered, list) and covered and all(nonempty(k) for k in covered) and
                        len(covered) == len(set(covered)) and not set(covered) & actual.keys(),
                        "rule_application duplicate/invalid rule mapping")
                if "rule_ids" in check:
                    require(set(covered) <= set(rules["effective_ids"]), "rule mapping contains unknown rule")
                actual.update({k: check for k in covered})
            require(set(rules["effective_ids"]) <= actual.keys(),
                    "rule_application missing/duplicate effective rule checks")
            for key in rules["effective_ids"]:
                check = actual[key]
                require(check.get("status") == "pass" and nonempty(check.get("note")) and
                        isinstance(check.get("evidence"), list) and check["evidence"] and
                        all(nonempty(name) for name in check["evidence"]),
                        "effective rule lacks observed pass/evidence: " + key)
                paths.extend(str(resolve(path.parent, name)) for name in check["evidence"])
            if application_phase == "after_reopen" and "SCH-G06" in rules["effective_ids"]:
                require(final.get("phase") == "after_reopen", "schematic final acceptance requires after_reopen phase")
                check_persistence(path, final)
    if op["status"] == "verified":
        if open_path:
            require("open_receipt" in op, "Open verification needs its actual acceptance receipt")
            if "open_persistence" in op:
                native = open_receipts.import_persistence(sys.modules[__name__], root, plan["open_plan"], op["open_persistence"], hashes)
                require(drawing.get("acceptanceScope", "page") == "local_display"
                        and resolve(root, native["summary"]["stageReceipt"]) == resolve(root, op["open_receipt"]),
                        "Local display persistence cannot verify another stage or a page delivery")
                require(any(c["id"] == "persistence" and c["status"] == "pass" for c in native["checks"]),
                        "Open save/reopen evidence did not pass")
                paths.extend(native["paths"])
                paths.extend(open_receipts.check_visual(sys.modules[__name__], root, plan["open_plan"],
                                                       op["open_receipt"], rows.get("visual_review"), hashes))
            else:
                require("persistence" in reports and drawing.get("acceptanceScope", "page") == "page",
                        "Open local display needs raw persistence evidence; page delivery needs its strict report")
                # Page acceptance keeps the existing guarded save/reopen proof.
                persistence = check_persistence(*reports["persistence"])
                final_file = resolve(root, op["open_receipt"])
                final_packet = read(final_file)
                require(persistence["target"] == drawing["target"] and
                        persistence["savedAt"] > datetime.fromisoformat(final_packet["completedAt"].replace("Z", "+00:00")),
                        "persistence belongs to another Open target or predates its final check")
                pinned_save = {resolve(persistence["saveReportPath"].parent, name): value
                               for name, value in persistence["saveReport"].get("inputs", {}).items()}
                require(pinned_save.get(resolve(root, plan["open_plan"]["path"])) == plan["open_plan"]["sha256"]
                        and pinned_save.get(final_file) == file_hash(final_file, hashes),
                        "guarded save must pin the current Open plan and final receipt")
        require(set(required) <= rows.keys(), "required checks missing")
        require(all(rows[k]["status"] == "pass" for k in required),
                "required checks must pass; unknown is not pass")
        require(all(c["status"] == "pass" for c in checks), "failed/unknown checks remain")
    return list(dict.fromkeys(paths))


def check_persistence(report_path, report):
    """Bind final acceptance to the guarded save and subsequent close/open readback."""
    pinned = {resolve(report_path.parent, p): h for p, h in report.get("inputs", {}).items()}
    def load_proof(name):
        path = resolve(report_path.parent, report["persistence"][name])
        require(path in pinned and file_hash(path) == pinned[path], "persistence evidence missing/stale: " + name)
        return path, read(path)
    save_report_path, save_report = load_proof("save_report")
    _, saved = load_proof("save_receipt")
    _, closed = load_proof("close_receipt")
    _, opened = load_proof("open_receipt")
    _, reopened = load_proof("reopened_snapshot")
    proof = saved.get("result", {}).get("workflowSave", {})
    require(save_report.get("phase") == "before_save" and save_report.get("rule_binding") == report.get("rule_binding") and
            proof.get("passed") is True and proof.get("phase") == "before_save" and
            proof.get("rule_binding") == report.get("rule_binding") and
            proof.get("reportSha256") == file_hash(save_report_path), "save receipt is not bound to reviewed rules")
    require(saved.get("ok") is True and saved.get("result", {}).get("saved") is True and
            closed.get("ok") is True and closed.get("result", {}).get("closed") is True and
            closed["result"].get("uuid") == proof.get("doc") and
            opened.get("ok") is True and opened.get("result", {}).get("ready") is True and reopened.get("ok") is True,
            "save/close/open/readback not confirmed")
    for packet in (saved, opened, reopened):
        context = packet.get("context", {})
        require(context.get("projectUuid") == proof.get("project") and context.get("documentUuid") == proof.get("doc") and
                context.get("documentType") == "schematic", "persistence target mismatch")
    stamps = [datetime.fromisoformat(p["createdAt"].replace("Z", "+00:00")) for p in (saved, closed, opened, reopened)]
    require(all(a < b for a, b in zip(stamps, stamps[1:])), "persistence receipts out of order")
    snapshot_path = resolve(save_report_path.parent, save_report["snapshot"])
    expected = {resolve(save_report_path.parent, p): h for p, h in save_report["inputs"].items()}
    require(snapshot_path in expected and file_hash(snapshot_path) == expected[snapshot_path], "saved snapshot changed")
    before, after = read(snapshot_path)["result"], reopened["result"]
    require(before.get("pageStateSha256") == proof.get("pageStateSha256") and after.get("saveGuardVersion") == 1,
            "persistence snapshot capability/fingerprint missing")
    # Native reopen can regenerate attribute IDs. Preserve the full attribute
    # multiset (parent, key, value, geometry, visibility); exclude only its own ID.
    def projection(snapshot):
        page = copy.deepcopy(snapshot["pagePrimitives"])
        page["attributes"] = sorted(json.dumps({k:v for k,v in a.items() if k != "primitiveId"}, sort_keys=True)
                                    for a in page["attributes"])
        return page
    require(projection(before) == projection(after), "saved/reopened page content changed")
    scripts = Path(__file__).resolve().parents[2] / "easyeda-agent/scripts/schematic_layout.py"
    spec = importlib.util.spec_from_file_location("schematic_layout", scripts)
    layout = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(layout)
    require(after.get("pinNetsAvailable") is True and layout.compare(before, after)["passed"], "reopened pin/net evidence failed")
    req_path = resolve(save_report_path.parent, save_report["requirements"])
    require(req_path in expected and file_hash(req_path) == expected[req_path], "saved acceptance scope changed")
    scope = read(req_path)["execution_rules"]["edit_scope"]
    acceptance = scope.get("acceptance", "page")
    require(proof.get("acceptanceScope", "page") == acceptance and acceptance in ("local", "page"), "save acceptance mismatch")
    mutable = copy.deepcopy(scope["mutable_ids"])
    for item in save_report.get("created_objects", []):
        mutable.setdefault(item["kind"], []).append(item["id"])
    measured = layout.audit_local(before, after, mutable) if acceptance == "local" else layout.audit(after, after["textMeasurements"])
    check_layout_review(report_path, report, measured, reopened, acceptance)
    return {"target": {"projectUuid": proof["project"], "documentUuid": proof["doc"]},
            "savedAt": stamps[0], "saveReportPath": save_report_path, "saveReport": save_report}


def check_layout_review(report_path, report, measured, snapshot=None, acceptance="page"):
    pinned = {resolve(report_path.parent, p): h for p, h in report.get("inputs", {}).items()}
    visual = report.get("visual_review")
    if visual is not None:
        # Visual readability is an observed engineering judgement, not text metrology.
        require(isinstance(visual, dict) and snapshot and visual.get("status") == "pass" and
                visual.get("snapshot_digest") == digest(snapshot) and visual.get("scope") == acceptance and
                nonempty(visual.get("note")), "missing/stale visual review")
        require(all(visual.get("checks", {}).get(k) is True for k in
                    ("text_legibility", "wire_clarity", "functional_readability")), "incomplete visual review")
        proofs = visual.get("evidence", [])
        require(isinstance(proofs, list) and proofs, "visual review needs actual image evidence")
        for value in proofs:
            path = resolve(report_path.parent, value)
            require(path.suffix.lower() in (".png", ".jpg", ".jpeg", ".svg", ".webp") and
                    path in pinned and file_hash(path) == pinned[path], "visual image changed/missing")
        native = snapshot.get("result", {}).get("pagePrimitives", {})
        text_ids = {v.get("primitiveId") for kind in ("attributes", "texts") for v in native.get(kind, [])}
        text_gaps = {"text_measurement_missing", "text_visibility_unknown", "visible_text_bbox_unavailable",
                     "attribute_read_incomplete"}
        require(all(v.get("kind") in text_gaps and v.get("id") in text_ids for v in measured["unknown"]),
                "non-text or unbound coverage remains unknown")
    else:
        require(not measured["unknown"], "layout coverage remains unknown")
    reviews = report.get("finding_reviews", [])
    require(isinstance(reviews, list), "finding_reviews must be an array")
    observations = {r.get("index"): r for r in reviews}
    require(len(observations) == len(reviews) and set(observations) == set(range(len(measured["findings"]))),
            "missing/duplicate/stale finding review")
    for index, finding in enumerate(measured["findings"]):
        review = observations[index]
        require(finding["kind"] in ("text_overlap", "crossing_candidate") and
                review.get("finding") == finding and review.get("status") == "pass" and nonempty(review.get("note")),
                "unresolved layout finding")
        proofs = review.get("evidence", [])
        require(isinstance(proofs, list) and proofs, "finding review needs actual evidence")
        for value in proofs:
            path = resolve(report_path.parent, value)
            require(path in pinned and file_hash(path) == pinned[path], "finding evidence changed/missing")
    return "visual" if visual is not None else "measured"


def verify_reopen(root, report_path):
    report_path = resolve(root, report_path)
    final = read(report_path)
    gate_path = resolve(report_path.parent, final["preflight"])
    checks = [{"id": key, "status": "pass", "note": "final reopened evidence", "report": str(path), "evidence": [str(path)]}
              for key, path in (("execution_rules", gate_path), ("rule_application", report_path))]
    paths = check_evidence(root, {"required_checks": ["execution_rules", "rule_application"]}, {"status": "verified", "checks": checks})
    require(all(Path(p).is_file() for p in paths), "final evidence missing")
    return {"passed": True, "phase": "after_reopen", "rule_binding": final["rule_binding"]}


def verify_save(root, report_path, live):
    """Read-only save preconditions using the existing rule/evidence validators.

    No workflow state is initialized. The Connector must compare the returned
    page fingerprint immediately before dispatching the native save.
    """
    scripts = Path(__file__).resolve().parents[2] / "easyeda-agent/scripts"
    def module(name):
        spec = importlib.util.spec_from_file_location(name, scripts / (name + ".py"))
        result = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(result)
        return result
    preflight, layout = module("schematic_preflight"), module("schematic_layout")
    report_path = resolve(root, report_path)
    report = read(report_path)
    require(report.get("phase") == "before_save", "explicit before_save report required")
    execution_root = resolve(root, report['execution_root'])
    execution_state = read(execution_root / '.workflow/state.json')
    require(report.get('execution_generation') == execution_state.get('generation'), 'execution evidence generation changed')
    require(not any(e.get('effective_state') in ('UNKNOWN', 'PARTIAL', 'APPLIED_INTERMEDIATE') for e in execution_state.get('execution', {}).get('actions', {}).values()), 'unresolved mutation; recover before save')
    hashes = {}
    pinned = {resolve(report_path.parent, p): h for p, h in report.get("inputs", {}).items()}
    def evidence(name):
        path = resolve(report_path.parent, report[name])
        require(path in pinned and file_hash(path, hashes) == pinned[path], "unpinned/stale " + name)
        return path, read(path)
    req_path, requirements = evidence("requirements")
    _, actions = evidence("plan")
    if actions.get("batch_id"):
        from execution_contract import action_identity
        entries = execution_state.get("execution", {}).get("actions", {})
        for action in actions["actions"]:
            entry = entries.get(action_identity(actions, action, digest), {})
            require(entry.get("effective_state") == "APPLIED_VERIFIED" and
                    entry.get("rule_binding") == actions.get("rule_binding") and
                    entry.get("target") == [actions["route"]["project"], actions["route"]["doc"]],
                    "planned action lacks a matching verified receipt")
    gate_path, gate = evidence("preflight")
    baseline_path, baseline = evidence("baseline")
    _, reviewed = evidence("snapshot")
    current = preflight.audit(requirements, actions, req_path.parent)
    require(current["passed"] and current["execution_rules"] == gate.get("execution_rules"),
            "current preflight does not match reviewed rules")
    rows = [{"id": key, "status": "pass", "note": "save preconditions", "evidence": [str(path)],
             "report": str(path)} for key, path in (("execution_rules", gate_path), ("rule_application", report_path))]
    paths = check_evidence(root, {"required_checks": ["execution_rules", "rule_application"]},
                           {"status": "verified", "checks": rows}, hashes, "before_save")
    for path in paths:
        path = Path(path).resolve()
        require(path.is_file(), "missing check evidence: " + str(path))
        if path not in (gate_path, report_path):
            require(path in pinned and file_hash(path, hashes) == pinned[path], "unpinned check evidence: " + str(path))
    target = requirements["target"]
    for field in ('runtimeInstance', 'mutationSeq', 'seqAbandoned'):
        require(field in reviewed and field in live and reviewed[field] == live[field], 'snapshot runtime/generation changed: ' + field)
    require(live.get('unordered') is not True and reviewed.get('unordered') is not True and
            type(live.get('seq')) is int and type(reviewed.get('seq')) is int and live['seq'] >= reviewed['seq'], 'snapshot ordering missing or stale')
    for name, snapshot in (("baseline", baseline), ("reviewed", reviewed), ("live", live)):
        context = snapshot.get("context", {})
        require(snapshot.get("ok") is True and context.get("projectUuid") == target["project"] and
                context.get("documentUuid") == target["doc"] and context.get("documentType") == "schematic",
                name + " snapshot identity/read failed")
    live_freshness = {k: live[k] for k in ('runtimeInstance', 'mutationSeq', 'seqAbandoned')}
    live_packet = live
    reviewed, live, baseline = map(layout.unwrap, (reviewed, live, baseline))
    require(all(s.get("pinNetsAvailable") is True and s.get("wiresAvailable") is True for s in (baseline, reviewed, live)),
            "pin/wire inventory coverage is not confirmed")
    require(live.get("saveGuardVersion") == 1 and reviewed.get("saveGuardVersion") == 1,
            "Connector save guard capability unavailable")
    fingerprint = live.get("pageStateSha256")
    require(isinstance(fingerprint, str) and re.fullmatch(r"[0-9a-f]{64}", fingerprint), "page fingerprint unavailable")
    require(fingerprint == reviewed.get("pageStateSha256") and
            live.get("pagePrimitives") == reviewed.get("pagePrimitives") and
            isinstance(live.get("textMeasurements"), dict) and
            live["textMeasurements"] == reviewed.get("textMeasurements") and
            layout.net_projection(live)[0] == layout.net_projection(reviewed)[0],
            "page changed since review; reread and recheck, do not save")
    scope = requirements["execution_rules"].get("edit_scope", {})
    mode = scope.get("mode", "layout")
    require(mode in ("layout", "design"), "unknown edit scope mode")
    require(scope.get("baseline_sha256") == file_hash(baseline_path, hashes), "baseline not bound to confirmed scope")
    mutable = copy.deepcopy(scope.get("mutable_ids"))
    require(isinstance(mutable, dict), "explicit mutable_ids scope required")
    # SDK-generated IDs are bound through planned creation receipts, never a free
    # post-write allowlist. Existing object changes still require confirmed IDs.
    created = report.get("created_objects", [])
    require(isinstance(created, list), "created_objects must be an array")
    seen = set()
    for item in created:
        kind, key, index = item["kind"], item["id"], item["plan_index"]
        require(kind in (("wires", "attributes", "components") if mode == "design" else ("wires", "attributes")) and isinstance(index, int) and not isinstance(index, bool) and
                0 <= index < len(actions["actions"]) and (kind, key) not in seen, "invalid/duplicate creation receipt")
        seen.add((kind, key))
        require(not any(r["primitiveId"] == key for r in baseline["pagePrimitives"][kind]), "created ID already in baseline")
        actual = [r for r in live["pagePrimitives"][kind] if r["primitiveId"] == key]
        require(len(actual) == 1, "created object missing from live inventory")
        receipt_path = resolve(report_path.parent, item["receipt"])
        require(receipt_path in pinned and file_hash(receipt_path, hashes) == pinned[receipt_path], "creation receipt missing/stale")
        receipt = read(receipt_path)
        require(receipt.get("ok") is True and receipt.get("context", {}).get("projectUuid") == target["project"] and
                receipt.get("context", {}).get("documentUuid") == target["doc"], "creation receipt failed/wrong target")
        result = layout.unwrap(receipt)
        require(result.get("primitiveId") == key and not result.get("partial") and result.get("writeState") != "unknown",
                "creation receipt not verified")
        action = actions["actions"][index]
        payload = action.get("payload", {})
        if kind == "wires":
            require(action["action"] == "schematic.wire.create", "unplanned wire creation")
            expected = {tuple(sorted((tuple(a), tuple(b)))) for a, b in preflight.segments(payload.get("points"))}
            observed = {tuple(sorted(((w["x0"], w["y0"]), (w["x1"], w["y1"])))) for w in live["wires"] if w["primitiveId"] == key}
            require(expected == observed, "created wire differs from planned geometry")
        elif kind == "attributes":
            attribute = actual[0]
            require(action["action"] == "schematic.netflag.create" and payload.get("kind") == "net_label" and
                    result.get("verified") is True and attribute.get("Key") == "Name" and
                    attribute.get("Value") == payload.get("net") and attribute.get("X") == payload.get("x") and
                    attribute.get("Y") == payload.get("y") and attribute.get("ValueVisible") is True and
                    any(w["primitiveId"] == attribute.get("ParentPrimitiveId") and w.get("net") == payload.get("net") for w in live["wires"]),
                    "created label does not match planned and connected visible net label")
        else:
            component = actual[0]
            require(action["action"] == "schematic.component.place" and component.get("componentType") == "part" and
                    nonempty(payload.get("designator")) and component.get("designator") == payload["designator"],
                    "created component not bound to planned placement")
        mutable.setdefault(kind, []).append(key)
    # Native-created dependent attributes remain tied to the confirmed creation.
    added_parts = {item["id"] for item in created if item["kind"] == "components"}
    added_owners = added_parts | {p["primitiveId"] for c in live["components"] if c["primitiveId"] in added_parts
                                 for p in c.get("pins", []) if p.get("primitiveId")}
    added_wires = {item["id"] for item in created if item["kind"] == "wires"}
    wire_nets = {w["primitiveId"]: w.get("net") for w in live["wires"] if w["primitiveId"] in added_wires}
    old_attributes = {a["primitiveId"] for a in baseline["pagePrimitives"]["attributes"]}
    mutable.setdefault("attributes", []).extend(a["primitiveId"] for a in live["pagePrimitives"]["attributes"]
        if a["primitiveId"] not in old_attributes and a["primitiveId"] not in mutable["attributes"] and
        (a.get("ParentPrimitiveId") in added_owners or (a.get("ParentPrimitiveId") in wire_nets and a.get("Key") == "Name" and
         a.get("Value") == wire_nets[a["ParentPrimitiveId"]])))
    scope_result = layout.compare_scope(baseline, live, mutable, preserve_identity=mode == "layout" or actions.get("rewire") is True)
    require(scope_result["passed"], "outside-scope or identity change: " + json.dumps({"total": len(scope_result["differences"]), "sample": [{k:v for k,v in d.items() if k in ("kind", "id", "reason")} for d in scope_result["differences"][:20]]}))
    net_changes = []
    if mode == "layout":
        require(layout.compare(baseline, live)["passed"], "pin connectivity changed")
    elif actions.get("rewire") is True and isinstance(scope.get("rewire"), dict):
        net_changes = layout.compare(baseline, live)["differences"]
    else:
        source = next((s for s in requirements["sources"] if s["id"] == scope.get("target_source")), None)
        require(source is not None, "confirmed expected design missing")
        source_path = resolve(req_path.parent, source["path"])
        require(file_hash(source_path, hashes) == source["sha256"], "expected design changed")
        expected = read(source_path)
        require(expected.get("projectId") == target["project"] and expected.get("documentId") == target["doc"], "expected design target mismatch")
        result = layout.compare_target(expected, live)
        require(result["passed"], "source design mismatch: " + json.dumps({"total": len(result["differences"]), "sample": result["differences"][:20]}))
        actual_parts = {c["designator"]: c for c in layout.parts(live)}
        for part in requirements.get("parts", []):
            if "pin_count" in part.get("required", {}):
                require(part["ref"] in actual_parts and len(actual_parts[part["ref"]].get("pins", [])) == part["required"]["pin_count"],
                        "source-backed pin count mismatch: " + part["ref"])
    acceptance = scope.get("acceptance", "page")
    require(acceptance in ("local", "page"), "unknown layout acceptance scope")
    measured = layout.audit_local(baseline, live, mutable) if acceptance == "local" else layout.audit(live, live["textMeasurements"])
    text_method = check_layout_review(report_path, report, measured, live_packet, acceptance)
    return {"passed": True, "phase": "before_save", "project": target["project"], "doc": target["doc"],
            **live_freshness, "execution_generation": execution_state['generation'],
            "pageStateSha256": fingerprint, "rule_binding": report["rule_binding"],
            "reportSha256": file_hash(report_path), "acceptanceScope": acceptance,
            "textVerification": text_method,
            "electricalChanges": net_changes,
            "preexistingLayout": {k: len(v) for k, v in measured.get("inherited", {}).items()}, "limits": "Save permission only; persistence and reopened verification remain pending."}


def apply(root, state, op):
    action = op["op"]
    if action == "source":
        new = source_value(root, op["source"])
        key = new["id"]
        require(key not in state["plan"] and key not in state["retired"], "ID already used by plan")
        old = state["sources"].get(key)
        if old and old != new:
            for item, why in impact(state, key).items():
                state["reviews"][item] = why + "; source refreshed"
        state["sources"][key] = new
    elif action == "propose":
        key = identity(op["id"])
        require(key not in state["pending"] and
                all(c["id"] != key for c in state["changes"]), "change ID already used")
        require(nonempty(op.get("reason")) and op.get("delta"), "reason and delta required")
        candidate = copy.deepcopy(state["plan"])
        seen = set()
        for delta in op["delta"]:
            target = identity(delta["id"])
            require(target not in seen, "duplicate delta ID")
            seen.add(target)
            kind = delta["action"]
            require(kind in ("ADDED", "MODIFIED", "REMOVED"), "invalid delta action")
            if kind == "ADDED":
                require(target not in candidate and target not in state["retired"], "ID already used")
            else:
                require(target in candidate, "unknown plan ID")
            if kind == "REMOVED":
                del candidate[target]
            else:
                item = delta["item"]
                fields = {"description", "acceptance", "sources", "depends_on", "objects", "domain"}
                require(fields <= set(item) <= fields | {"required_checks", "jev", "pcb_constraint_ir", "pcb_checks", "open_plan"},
                        "plan fields must match schema")
                if item.get("domain") == "pcb":
                    pcb_constraints.validate(sys.modules[__name__], item.get("pcb_constraint_ir"))
                    pcb_constraints.validate_checks(sys.modules[__name__], item.get("pcb_checks"),
                                                    item["pcb_constraint_ir"]["target"], item["sources"])
                if "jev" in item:
                    validate_jev(item["jev"])
                candidate[target] = copy.deepcopy(item)
        validate_plan(candidate, state["sources"], root)
        state["pending"][key] = dict(op, base=digest(state["plan"]),
                                      source_base=digest(state["sources"]), created=now())
    elif action == "approve":
        change = state["pending"][op["id"]]
        require(nonempty(op.get("confirmation")), "actual user confirmation locator required")
        require(change["base"] == digest(state["plan"]) and
                change["source_base"] == digest(state["sources"]), "proposal stale; re-propose")
        impacted = {}
        for delta in change["delta"]:
            key = delta["id"]
            if key in state["plan"]:
                impacted.update(impact(state, key))
            if delta["action"] == "REMOVED":
                del state["plan"][key]
                state["retired"].append(key)
                state["reviews"].pop(key, None)
            else:
                rev = state["plan"].get(key, {}).get("revision", 0) + 1
                state["plan"][key] = dict(delta["item"], revision=rev,
                                         approval=op["confirmation"], review_epoch=0)
        validate_plan(state["plan"], state["sources"], root)
        for delta in change["delta"]:
            if delta["id"] in state["plan"]:
                impacted.update(impact(state, delta["id"]))
        for key, reason in impacted.items():
            if key in state["plan"] and not any(
                    d["id"] == key and d["action"] == "ADDED" for d in change["delta"]):
                state["reviews"][key] = reason + "; approved change " + op["id"]
        state["changes"].append(dict(change, confirmation=op["confirmation"], approved=now()))
        del state["pending"][op["id"]]
    elif action == "withdraw":
        require(nonempty(op.get("reason")), "withdrawal reason required")
        change = state["pending"].pop(op["id"])
        state["changes"].append(dict(change, withdrawn=now(), withdrawal_reason=op["reason"]))
    elif action == "review":
        key = op["item"]
        require(key in state["reviews"] or
                status(root, state)["items"][key]["status"] == "needs_review",
                "item is not awaiting review")
        require(nonempty(op.get("reason")), "review rationale required")
        require(op["outcome"] in ("unchanged", "reverify"), "use unchanged or reverify")
        require(not any(source_issue(root, state["sources"][s])
                        for s in state["plan"][key]["sources"]), "refresh invalid sources first")
        p = state["plan"][key]
        if op["outcome"] == "unchanged":
            # Preserve historical result; append explicit carry-forward assessment.
            previous = next((r for r in reversed(state["results"])
                             if r["item"] == key and r["revision"] == p["revision"] and
                             r["status"] == "verified"), None)
            if previous:
                require(all(resolve(root, e["path"]).is_file() and
                            file_hash(resolve(root, e["path"])) == e["hash"]
                            for e in previous["evidence"]), "old evidence changed or missing")
                state["results"].append(dict(previous, basis=basis(state, key),
                                             at=now(), carry_forward_reason=op["reason"]))
        else:
            p["review_epoch"] = p.get("review_epoch", 0) + 1
        state["changes"].append({"id": "REVIEW-" + str(state["generation"] + 1),
                                 "item": key, "outcome": op["outcome"],
                                 "reason": op["reason"], "at": now()})
        state["reviews"].pop(key, None)
    elif action in ("pcb_dry_run", "pcb_apply"):
        key = identity(op["item"])
        require(key in state["plan"], "unknown PCB module")
        p = state["plan"][key]
        require(op["revision"] == p["revision"], "PCB preparation targets old revision")
        require(status(root, state)["items"][key]["status"] != "needs_review", "resolve module/source review before preparation")
        applying = action == "pcb_apply"
        require(not applying or all(status(root, state)["items"][d]["status"] == "verified" for d in p["depends_on"]),
                "dependencies not verified before PCB rule apply")
        receipt = pcb_constraints.run(sys.modules[__name__], root, key, p, op.get("window"), apply=applying)
        confirmed = receipt.get("rules_applied") if applying else receipt["status"] == "ready"
        field = "pcb_constraint_apply" if applying else "pcb_constraint_dry_run"
        state["results"].append({"op": action, "item": key, "revision": p["revision"],
            "status": "partial" if confirmed else "blocked", "preparation_only": True,
            "note": ("PCB规则apply；绑定回读：" + str(bool(confirmed)) + "；原生DRC：" + str(receipt.get("board_status"))
                     if applying else "PCB模块只读准备：" + receipt["status"] + "；未apply或布局/布线"), field: receipt,
            "evidence": [{"path": receipt[k], "hash": file_hash(receipt[k])} for k in ("ir_file", "report")],
            "basis": basis(state, key), "at": now()})
    elif action == "result":
        key = op["item"]
        require(key in state["plan"], "unknown plan item")
        p = state["plan"][key]
        require(op["revision"] == p["revision"], "result targets old revision")
        current = status(root, state)
        require(current["items"][key]["status"] != "needs_review", "resolve review first")
        require(all(current["items"][d]["status"] == "verified" for d in p["depends_on"]),
                "dependencies not verified")
        require(op["status"] in ("in_progress", "partial", "blocked", "verified"), "invalid result status")
        require(op["status"] not in ("in_progress", "verified") or p.get("domain") in DOMAINS,
                "classify legacy execution domain through propose/approve before starting/verifying")
        require(nonempty(op.get("note")), "actual action/readback note required")
        require("jev" not in op, "Jev receipts are written only by the workflow")
        require("pcb_constraint_dry_run" not in op and "pcb_constraint_apply" not in op and "pcb_constraint_review" not in op and "preparation_only" not in op,
                "PCB compiler receipts are written only by the workflow")
        require("open_import" not in op, "Open import summaries are written only by the workflow")
        require("open_persistence_import" not in op, "Open persistence summaries are written only by the workflow")
        if "open_plan" in p and op["status"] == "verified":
            require("open_receipt" in op, "A bound Open plan needs its actual final receipt before verification")
        if "open_receipt" in op:
            require(p.get("domain") == "schematic" and "open_plan" in p, "Open receipt needs a bound schematic plan")
            imported = open_receipts.import_receipt(sys.modules[__name__], root, p["open_plan"], op["open_receipt"])
            if op["status"] == "verified":
                if imported["summary"].get("acceptanceScope", "page") == "local_display":
                    require(all(any(c["id"] == name and c["status"] == "pass" for c in imported["checks"])
                                for name in ("open_stage_receipt", "open_local_rules", "open_requirements")),
                            "Local display acceptance needs actual attribute, identity and requirement evidence")
                else:
                    require(imported["summary"]["stage"]["check"] == "final" and any(c["id"] == "open_target_check"
                            and c["status"] == "pass" for c in imported["checks"]),
                            "Geometry receipts cannot verify the bound full Open target")
                requirement_rows = imported["summary"].get("requirementResults", [])
                require(not requirement_rows or (any(c["id"] == "open_requirements" and c["status"] == "pass"
                        for c in imported["checks"]) and all(row.get("severity") != "error" or row.get("status") == "pass"
                                                         for row in requirement_rows)),
                        "All applicable Open error requirements need current evidence before verification")
            checks = op.get("checks", [])
            require(isinstance(checks, list) and not any(isinstance(c, dict) and c.get("id") in
                    ("open_stage_receipt", "open_target_check", "open_local_rules", "open_requirements") for c in checks), "Open checks come only from the receipt")
            op = dict(op, checks=checks + imported["checks"],
                      evidence=list(dict.fromkeys(op.get("evidence", []) + imported["paths"])), open_import=imported["summary"])
        else:
            require(not any(isinstance(c, dict) and c.get("id") in
                    ("open_stage_receipt", "open_target_check", "open_local_rules", "open_requirements")
                    for c in op.get("checks", [])), "Open checks require an actual receipt")
        if "open_persistence" in op:
            require("open_plan" in p and "open_receipt" in op, "Open persistence needs a bound plan and actual stage receipt")
            require("execution_rules" not in p.get("required_checks", []), "Native Open persistence cannot be mixed with legacy acceptance")
            saved = open_receipts.import_persistence(sys.modules[__name__], root, p["open_plan"], op["open_persistence"])
            require(resolve(root, saved["summary"]["stageReceipt"]) == resolve(root, op["open_receipt"]),
                    "Open persistence belongs to another stage receipt")
            require(not any(c.get("id") == "persistence" for c in op.get("checks", []) if isinstance(c, dict)),
                    "Open persistence check comes only from its original receipts")
            op = dict(op, checks=op.get("checks", []) + saved["checks"],
                      evidence=list(dict.fromkeys(op.get("evidence", []) + saved["paths"])), open_persistence_import=saved["summary"])
        require(isinstance(op.get("retry_decisions", False), bool), "retry_decisions must be boolean")
        if op["status"] == "in_progress" and current["recovery"].get(key, {}).get("readback_required"):
            require(any(isinstance(c, dict) and c.get("id") == "recovery_readback" and
                        c.get("status") == "pass" for c in op.get("checks", [])),
                    "recovery_readback pass/evidence required before resuming unfinished hardware actions")
        evidence = []
        hashes = {}
        for name in dict.fromkeys(op.get("evidence", []) + check_evidence(root, p, op, hashes)):
            f = resolve(root, name)
            require(f.is_file(), "evidence missing: " + str(f))
            evidence.append({"path": str(f), "hash": file_hash(f, hashes)})
        if op["status"] == "verified":
            require(evidence and nonempty(op.get("artifact")) and
                    op.get("checks_passed") is True and op.get("saved") is True,
                    "verified requires artifact identity, evidence, checks and save")
            if p.get("domain") == "pcb":
                applied = next((r for r in reversed(state["results"]) if r["item"] == key and
                                r["basis"] == basis(state, key) and r.get("pcb_constraint_apply")), None)
                native = applied.get("pcb_constraint_apply", {}) if applied else {}
                require(native.get("rules_applied") is True and native.get("drc_checked") is True and nonempty(op.get("window")),
                        "PCB verified requires rule readback and explicit window for fresh post-route review")
                require(all(resolve(root, e["path"]).is_file() and
                            file_hash(resolve(root, e["path"])) == e["hash"] for e in applied["evidence"]),
                        "PCB native apply evidence changed or missing")
                review = pcb_constraints.run(sys.modules[__name__], root, key, p, op.get("window"), review=True)
                op = dict(op, pcb_constraint_review=review)
                evidence.extend({"path": review[k], "hash": file_hash(review[k])} for k in ("ir_file", "report"))
                if not (review.get("bindings_verified") and review.get("board_status") == "pass" and
                        review.get("geometry_status") == "pass" and review.get("professional_status") == "pass" and
                        review.get("snapshot_stable") and review["status"] == "pass"):
                    op = dict(op, requested_status="verified", status="partial",
                              note=op["note"] + "; post-route read-only review: " + review["status"])
        if p.get("domain") == "pcb" and op["status"] == "in_progress":
            receipt = pcb_constraints.run(sys.modules[__name__], root, key, p, op.get("window"), apply=True)
            op = dict(op, pcb_constraint_apply=receipt,
                      note=op["note"] + "; PCB规则绑定回读：" + str(receipt["rules_applied"]) +
                           "; 原生DRC：" + str(receipt.get("board_status")))
            evidence.extend({"path": receipt[k], "hash": file_hash(receipt[k])} for k in ("ir_file", "report"))
            if not receipt["rules_applied"]:
                op = dict(op, requested_status="in_progress", status="blocked", preparation_only=True,
                          note=op["note"] + "; PCB Constraint apply " + receipt["status"])
        adopted = op.get("decision_selections", {})
        require(isinstance(adopted, dict), "decision_selections must be an object")
        receipt = decisions_for(state, key, op.get("retry_decisions", False))
        decisions = receipt.get("decisions", {})
        pending = []
        for name, item in decisions.items():
            report = item["report"]
            ids = [c["id"] for c in p["jev"]["requests"][name]["candidates"]]
            if not (report.get("attempted") is True and report.get("status") == "recommended"
                    and report.get("fallback") is None and report.get("selected") in ids
                    and nonempty(report.get("model"))):
                pending.append(name)
        if op["status"] == "verified":
            pending.extend(name for name, item in decisions.items()
                           if adopted.get(name) != item["report"].get("selected"))
        if pending:
            op = dict(op, requested_status=op["status"], status="blocked",
                      decision_blockers=sorted(set(pending)))
        state["results"].append(dict(op, jev=receipt, evidence=evidence, basis=basis(state, key), at=now()))
    elif action == "context":
        allowed = {"stage", "coordinator", "tasks", "authorization", "questions", "blockers", "next"}
        require(isinstance(op["value"], dict) and set(op["value"]) <= allowed, "invalid context fields")
        state["context"].update(op["value"])
    else:
        raise ValueError("unknown operation")
    state["generation"] += 1
    validate_plan(state["plan"], state["sources"])
    return state


def history(state):
    # Only plan and change history. No parsed files, execution results or source copies.
    return {"schema": 1, "goal": state["goal"], "plan": state["plan"],
            "changes": state["changes"], "retired": state["retired"]}


def escaped(value):
    return str(value).replace("|", r"\|").replace("\n", " ")


def view_contents(root, state, current=None):
    current = status(root, state) if current is None else current
    plan = [MARKER, "# 当前执行方案", "", "目标：" + state["goal"],
            "数据修订：" + str(state["generation"]), "",
            "结构化来源：.workflow/state.json；此文件为生成视图，不手工维护。", "",
            "| ID / 修订 | 要求 | 依据 | 依赖 / 共用对象 | 验收 |",
            "|---|---|---|---|---|"]
    for key, p in state["plan"].items():
        plan.append("| " + " | ".join(map(escaped, [key + " / " + str(p["revision"]),
                    p["description"], ", ".join(p["sources"]),
                    ", ".join(p["depends_on"] + p["objects"]), p["acceptance"]])) + " |")
    if any(p.get("required_checks") for p in state["plan"].values()):
        plan += ["", "## 必需检查项"]
        plan += ["- " + key + "：" + ", ".join(p["required_checks"])
                 for key, p in state["plan"].items() if p.get("required_checks")]
    for key, p in state["plan"].items():
        if p.get("domain") != "pcb":
            continue
        latest = next((r for r in reversed(state["results"]) if r["item"] == key and
                       r["basis"] == basis(state, key) and (r.get("pcb_constraint_review") or r.get("pcb_constraint_apply") or r.get("pcb_constraint_dry_run"))), None)
        if latest:
            plan += pcb_constraints.review_lines(sys.modules[__name__], key, latest.get("pcb_constraint_review") or latest.get("pcb_constraint_apply") or latest["pcb_constraint_dry_run"])
        else:
            plan += ["", "### " + key + " PCB Constraint apply", "- 尚未取得当前修订的规则回读；启动时自动apply并调用原生DRC，不能冒称整板通过。"]
    for key, p in state["plan"].items():
        if p.get("open_plan"):
            plan += ["", "### " + key + " Open方案绑定", "- 文件：" + escaped(p["open_plan"]["path"]),
                     "- SHA256：" + p["open_plan"]["sha256"], "- 阶段回执不代表视觉、整页交付或保存重开通过。"]
    plan += ["", "## Jev 自动决策策略", "未登记语义请求的项不调用；确定性任务统一说明一次，不逐项记录跳过。"]
    for key, p in state["plan"].items():
        policy = p.get("jev", {})
        if "requests" in policy:
            plan.append("- " + key + "：自动调用 " + escaped(", ".join(policy["requests"])))
    plan += ["", "## 确认与依据定位"]
    for key, p in state["plan"].items():
        plan.append("- " + key + "：" + escaped(p["approval"]))
    for key, s in state["sources"].items():
        plan.append("- " + key + "：" + escaped(s.get("locator") or
                    (s.get("manifest", "") + " #" + ",".join(s.get("anchors", [])))))
    plan += ["", "## 待讨论变更（尚未生效）"]
    plan += ["- " + key + "：" + escaped(c["reason"]) for key, c in state["pending"].items()]
    progress = [MARKER, "# 执行与验收", "", "| ID | 修订 | 状态 |", "|---|---|---|"]
    progress += [f"| {key} | {r['revision']} | {r['status']} |" for key, r in current["items"].items()]
    progress += ["", "## 最近执行证据（完整记录见 state.json）"]
    for r in state["results"][-10:]:
        progress.append(f"- {r['item']} r{r['revision']} {r['status']}：{escaped(r['note'])}")
        progress += ["  - 检查 " + escaped(c["id"]) + "：" + escaped(c["status"])
                     for c in r.get("checks", [])]
        if r.get("open_import"):
            imported = r["open_import"]
            progress += ["  - Open阶段：" + escaped(imported["stage"]), "  - 回执：" + escaped(imported["receiptFile"]),
                         "  - 覆盖详表（仅该回执范围）：", "", "| 要求 | 绑定 | 检查机制 | 覆盖/未覆盖 | 证据 | 结果 |", "|---|---|---|---|---|---|"]
            for c in r.get("checks", []):
                if "requirement" in c:
                    progress.append("| " + " | ".join(map(escaped, [c["requirement"], c["binding"], c["enforcement"],
                                    c["coverage"], ", ".join(c["evidence"]), c["status"]])) + " |")
            progress.append("")
        progress += ["  - " + escaped(e["path"]) for e in r["evidence"]]
        for name, decision in r.get("jev", {}).get("decisions", {}).items():
            report = decision["report"]
            progress.append("  - Jev " + escaped(name) + "：" + escaped({k: report.get(k) for k in
                            ("attempted", "status", "selected", "model", "ms", "fallback")}))
        if r.get("decision_blockers"):
            progress.append("  - 决策未完成/未采用：" + ", ".join(r["decision_blockers"]))
    progress += ["", "## 交接摘要", "- 目标：" + escaped(state["goal"]),
                 "- 数据修订：" + str(state["generation"]),
                 "- 当前可执行：" + ", ".join(current["ready"]),
                 "- 待复核：" + ", ".join(k for k, v in current["items"].items()
                                      if v["status"] == "needs_review"),
                 "- 来源问题：" + escaped(current["source_issues"]),
                 "- Open方案问题：" + escaped(current.get("open_plan_issues", {})),
                 "- 接续先现场读回；in_progress/partial 不能直接重复执行。"]
    progress += ["- " + k + "：" + escaped(v) for k, v in state["context"].items()]
    return {"task_plan.md": "\n".join(plan) + "\n",
            "progress.md": "\n".join(progress) + "\n"}


def view_issues(root, state, current=None):
    issues = {}
    for name, expected in view_contents(root, state, current).items():
        path = root / name
        if not path.exists():
            issues[name] = "missing"
        elif path.read_text(encoding="utf-8") != expected:
            issues[name] = "differs from authoritative state; inspect before reconciliation"
    return issues


def render(root, state):
    for name, content in view_contents(root, state).items():
        f = root / name
        require(not f.exists() or MARKER in f.read_text(encoding="utf-8"),
                name + " is unmanaged; migrate explicitly, do not overwrite")
        write(f, content)


def reconcile(root, state, reason):
    issues = view_issues(root, state)
    require(not issues or nonempty(reason),
            "views differ; inspect differences, then use --reconcile-views REASON")
    if issues:
        expected = view_contents(root, state)
        state["generation"] += 1
        state["changes"].append({
            "id": "RECONCILE-" + str(state["generation"]), "at": now(), "reason": reason,
            "views": {name: {"issue": issue,
                      "observed_hash": file_hash(root / name) if (root / name).is_file() else None,
                      "pre_reconcile_expected_hash": hashlib.sha256(expected[name].encode("utf-8")).hexdigest()}
                      for name, issue in issues.items()}})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init").add_argument("--goal", required=True)
    p = sub.add_parser("apply")
    p.add_argument("file", type=Path)
    p.add_argument("--expect-generation", required=True, type=int)
    p.add_argument("--reconcile-views", metavar="REASON")
    sub.add_parser("check")
    sub.add_parser("next")
    sub.add_parser("execution")
    p = sub.add_parser("verify-save")
    p.add_argument("--report", required=True)
    p = sub.add_parser("verify-reopen")
    p.add_argument("--report", required=True)
    sub.add_parser("render").add_argument("--reconcile-views", metavar="REASON")
    sub.add_parser("show").add_argument("id")
    sub.add_parser("impact").add_argument("id")
    p = sub.add_parser("checkpoint")
    p.add_argument("--message", required=True)
    args = parser.parse_args()
    root = args.root.resolve()
    if args.cmd == "verify-save":
        print(json.dumps(verify_save(root, args.report, json.load(sys.stdin)), ensure_ascii=False))
        return
    if args.cmd == "verify-reopen":
        print(json.dumps(verify_reopen(root, args.report), ensure_ascii=False))
        return
    path = root / ".workflow/state.json"
    if args.cmd == "init":
        require(not path.exists(), "already initialized")
        for name in ("task_plan.md", "progress.md"):
            require(not (root / name).exists(), "existing plan: explicit migration required")
        state = {"schema": 1, "generation": 0, "goal": args.goal, "sources": {},
                 "plan": {}, "pending": {}, "changes": [], "retired": [],
                 "reviews": {}, "results": [], "context": {}}
        write(path, state)
        write(path.parent / ".gitignore", "*\n!.gitignore\n!plan-history.json\n")
        render(root, state)
        print(json.dumps({"generation": 0}))
        return
    state = read(path)
    require(state.get("schema") == 1, "unsupported state schema")
    validate_plan(state["plan"], state["sources"])
    if args.cmd == "execution":
        import execution_contract
        lock = path.with_suffix('.lock')
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        try:
            state = read(path)
            data = json.load(sys.stdin)
            result = execution_contract.operate(sys.modules[__name__], root, state, data)
            if data['operation'] != 'inspect':
                write(path, state)
                render(root, state)
            print(json.dumps(result, ensure_ascii=False))
        finally:
            os.close(fd)
            lock.unlink()
        return
    if args.cmd == "apply":
        require(state["generation"] == args.expect_generation, "state changed; reload before update")
        # One writer by contract; lock prevents simultaneous read-modify-write.
        lock = path.with_suffix(".lock")
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        try:
            state = read(path)
            require(state["generation"] == args.expect_generation, "state changed")
            reconcile(root, state, args.reconcile_views)
            operation = read(args.file)
            state = apply(root, copy.deepcopy(state), operation)
            for name in ("task_plan.md", "progress.md"):
                require(not (root / name).exists() or
                        MARKER in (root / name).read_text(encoding="utf-8"), "unmanaged view")
            write(path, state)  # Authoritative write; render is recoverable with 'render'.
            render(root, state)
        finally:
            os.close(fd)
            lock.unlink()
        result = {"generation": state["generation"]}
        if operation["op"] in ("result", "pcb_dry_run", "pcb_apply"):
            result.update({k: state["results"][-1].get(k) for k in ("status", "jev", "decision_blockers")})
            if state["results"][-1].get("pcb_constraint_dry_run"):
                result["pcb_constraint_dry_run"] = state["results"][-1]["pcb_constraint_dry_run"]
            if state["results"][-1].get("pcb_constraint_apply"):
                result["pcb_constraint_apply"] = state["results"][-1]["pcb_constraint_apply"]
            if state["results"][-1].get("pcb_constraint_review"):
                result["pcb_constraint_review"] = state["results"][-1]["pcb_constraint_review"]
        print(json.dumps(result, ensure_ascii=False))
    elif args.cmd in ("check", "next"):
        current = status(root, state)
        current["view_issues"] = view_issues(root, state, current)
        current["recovery_blocked"] = bool(current["view_issues"])
        if current["recovery_blocked"]:
            current["ready"] = []
        print(json.dumps(current, ensure_ascii=False, indent=2))
        if args.cmd == "next" and current["recovery_blocked"]:
            raise SystemExit(2)
    elif args.cmd == "render":
        lock = path.with_suffix(".lock")
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        try:
            state = read(path)
            validate_plan(state["plan"], state["sources"])
            for name in ("task_plan.md", "progress.md"):
                require(not (root / name).exists() or
                        MARKER in (root / name).read_text(encoding="utf-8"), "unmanaged view")
            reconcile(root, state, args.reconcile_views)
            write(path, state)
            render(root, state)
        finally:
            os.close(fd)
            lock.unlink()
    elif args.cmd == "impact":
        print(json.dumps(impact(state, args.id), ensure_ascii=False, indent=2))
    elif args.cmd == "show":
        print(json.dumps(state["plan"].get(args.id) or state["sources"].get(args.id),
                         ensure_ascii=False, indent=2))
    elif args.cmd == "checkpoint":
        # Reuse existing repository; stage/commit this file only, never git add -A or push.
        subprocess.run(["git", "-C", str(root), "rev-parse", "--show-toplevel"],
                       check=True, capture_output=True)
        tracked = path.parent / "plan-history.json"
        write(tracked, history(state))
        rel = ".workflow/plan-history.json"
        subprocess.run(["git", "-C", str(root), "add", "--", rel], check=True)
        subprocess.run(["git", "-C", str(root), "commit", "--only", "-m", args.message,
                        "--", rel], check=True)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    try:
        main()
    except (ValueError, KeyError, TypeError, OSError, subprocess.CalledProcessError) as e:
        raise SystemExit(str(e))
